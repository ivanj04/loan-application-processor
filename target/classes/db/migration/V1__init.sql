-- Loan Application Processor - Initial Schema
-- Note: Spring Batch meta-tables are managed by Spring Batch itself (initialize-schema: always)

CREATE TABLE IF NOT EXISTS batch_job_records (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id          VARCHAR(36)    NOT NULL UNIQUE,
    file_name         VARCHAR(255)   NOT NULL,
    total_records     INT            NOT NULL DEFAULT 0,
    processed_records INT            NOT NULL DEFAULT 0,
    approved_count    INT            NOT NULL DEFAULT 0,
    rejected_count    INT            NOT NULL DEFAULT 0,
    review_count      INT            NOT NULL DEFAULT 0,
    started_at        TIMESTAMP,
    completed_at      TIMESTAMP,
    status            VARCHAR(20)    NOT NULL DEFAULT 'RUNNING'
);

CREATE TABLE IF NOT EXISTS loan_applications (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id       VARCHAR(50)    NOT NULL UNIQUE,
    borrower_name        VARCHAR(255)   NOT NULL,
    borrower_ssn         VARCHAR(20),
    loan_amount          NUMERIC(15,2)  NOT NULL,
    property_value       NUMERIC(15,2)  NOT NULL,
    annual_income        NUMERIC(15,2)  NOT NULL,
    credit_score         INT            NOT NULL,
    loan_type            VARCHAR(20)    NOT NULL,
    status               VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    risk_score           INT            NOT NULL DEFAULT 0,
    processing_batch_id  VARCHAR(36),
    created_at           TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_batch FOREIGN KEY (processing_batch_id) REFERENCES batch_job_records(batch_id)
);

CREATE INDEX IF NOT EXISTS idx_loan_app_status ON loan_applications(status);
CREATE INDEX IF NOT EXISTS idx_loan_app_loan_type ON loan_applications(loan_type);
CREATE INDEX IF NOT EXISTS idx_loan_app_batch ON loan_applications(processing_batch_id);
CREATE INDEX IF NOT EXISTS idx_batch_job_status ON batch_job_records(status);
